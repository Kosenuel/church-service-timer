"""Build deterministic 1-bit display fonts from official Liberation 2.1.5 TTFs.
Usage: python scripts/build-font-atlas.py --source PATH_TO_EXTRACTED_FONTS
Requires Pillow 12.3.0. The original Cuekeeper Matrix JSON is never modified.
"""
import argparse
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
chars = list(json.loads((root/'assets/pixel_fonts/cuekeeper_matrix.json').read_text())['glyphs'])
atlas = {}
for family, label in [('Serif', 'service_serif'), ('Sans', 'clear_sans')]:
    for height in [7, 14]:
        for variant, suffix in enumerate(['Regular', 'Bold', 'Italic', 'BoldItalic']):
            font = ImageFont.truetype(str(args.source/f'Liberation{family}-{suffix}.ttf'), 20)
            bounds = [font.getbbox(c, anchor='ls') for c in chars if c != ' ']
            top = min(b[1] for b in bounds)
            bottom = max(b[3] for b in bounds)
            scale = height / (bottom - top)
            table = {}
            for char in chars:
                if char == ' ':
                    table[char] = '/'.join(['0' * max(2, round(font.getlength(' ') * scale))] * height)
                    continue
                box = font.getbbox(char, anchor='ls')
                width = max(1, box[2] - box[0])
                mask = Image.new('L', (width, bottom-top))
                ImageDraw.Draw(mask).text((-box[0], -top), char, font=font, fill=255, anchor='ls')
                mask = mask.resize((max(1, round(width * scale)), height), Image.Resampling.LANCZOS)
                binary = mask.point(lambda n: 255 if n >= 78 else 0, '1')
                bbox = binary.getbbox()
                # Preserve common baseline, trim only horizontal blank columns.
                if bbox:
                    binary = binary.crop((bbox[0], 0, bbox[2], height))
                table[char] = '/'.join(''.join('1' if binary.getpixel((x,y)) else '0' for x in range(binary.width)) for y in range(height))
            atlas[f'{label}_{height//7}_{variant}'] = table

header = '// Generated by scripts/build-font-atlas.py. Do not edit by hand.\n// Derived from Liberation 2.1.5; see assets/pixel_fonts/OFL-Liberation.txt.\n'
lines = [header, 'const fontAtlas = <String, Map<String, String>>{']
for key, table in atlas.items():
    lines.append(f'  "{key}": {{')
    for char, bits in table.items():
        lines.append('    ' + json.dumps(char) + ': ' + json.dumps(bits) + ',')
    lines.append('  },')
lines.append('};\n')
(root/'lib/font_atlas.dart').write_text('\n'.join(lines), encoding='utf-8')
(root/'assets/pixel_fonts/alternate_fonts.json').write_text(json.dumps(atlas, indent=2), encoding='utf-8')
print(f'Generated {len(atlas)} font/size/style combinations, {len(chars)} glyphs each.')
